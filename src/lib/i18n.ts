function idiomaInicial(): Idioma {
  if (typeof window === 'undefined') return 'pt-BR';
  return window.localStorage.getItem(STORAGE_KEY) === 'zh-CN' ? 'zh-CN' : 'pt-BR';
}

export function useIdioma() {
  const [idioma, setIdiomaState] = useState<Idioma>(idiomaInicial);

  useEffect(() => {
    document.documentElement.lang = idioma;
    window.localStorage.setItem(STORAGE_KEY, idioma);
  }, [idioma]);

  function setIdioma(proximo: Idioma) {
    setIdiomaState(proximo);
  }

  function t(chave: ChaveTexto, params?: Record<string, string | number>): string {
    let texto = textos[idioma][chave] ?? (idioma === 'zh-CN' ? fallbackIngles[chave] : undefined) ?? textos['pt-BR'][chave] ?? chave;
    if (params) {
      for (const [key, value] of Object.entries(params)) {
        texto = texto.replaceAll(`{${key}}`, String(value));
      }
    }
    return texto;
  }

  return { idioma, setIdioma, t };
}
